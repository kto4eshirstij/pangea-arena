#!/usr/bin/env python3
# Pangea Arena — tier-0 weapons: generate scripts/pangea_weapons.shader, audit and zip the pak.
# GPLv2+. System Python (no Blender).
#
#   python3 tools/weapons/pack.py [content/pangea] [content/build]
#
# Output: <build>/arena-weapons-<sha8>.pk3, sha8 = first 8 hex of sha256 of the zip bytes
# (deterministic: sorted entries, fixed timestamps).
import glob
import hashlib
import io
import json
import os
import sys
import zipfile

ALLOWED = ("models/weapons2/", "models/hands/", "models/projectiles/", "icons/iconw_",
           "scripts/pangea_weapons.shader")
FLAME = "models/weapons2/torch/flame"
FLAME_FRAMES = 8


def shader_text(metas):
    out = ["// Pangea Arena tier-0 weapons. Generated by tools/weapons/pack.py, do not edit.",
           "// Flame: two crossed planes, %d-frame animMap + vertex wobble, additive." % FLAME_FRAMES,
           "",
           FLAME,
           "{",
           "\tcull disable",
           "\tsort additive",
           "\tnomipmaps",
           "\tdeformVertexes wave 10 sin 0 0.45 0 2.3",
           "\t{",
           "\t\tanimMap 15 " + " ".join("%s%d.tga" % (FLAME, k + 1) for k in range(FLAME_FRAMES)),
           "\t\tblendFunc add",
           "\t\trgbGen identity",
           "\t}",
           "}",
           ""]
    for m in sorted(metas, key=lambda m: m["id"]):
        if not m.get("glow"):
            continue
        base = "%s/%s" % (m["qdir"], m["id"])
        names = [base] + ["%s_paint%d" % (base, k) for k in range(1, m["paint"] + 1)]
        out.append("// %s: diffuse + smouldering embers (glow mask pulses)" % m["id"])
        for n in names:
            out += [n, "{",
                    "\t{", "\t\tmap %s.tga" % n, "\t\trgbGen lightingDiffuse", "\t}",
                    "\t{", "\t\tmap %s_glow.tga" % base, "\t\tblendFunc add",
                    "\t\trgbGen wave sin 0.75 0.25 0 1.6", "\t}",
                    "}", ""]
    return "\n".join(out)


def main():
    pak = sys.argv[1] if len(sys.argv) > 1 else "content/pangea"
    build = sys.argv[2] if len(sys.argv) > 2 else "content/build"
    metas = []
    for p in sorted(glob.glob(os.path.join(build, "weapons-meta", "*.json"))):
        with open(p) as f:
            d = json.load(f)
        if "id" in d:
            metas.append(d)
    os.makedirs(os.path.join(pak, "scripts"), exist_ok=True)
    with open(os.path.join(pak, "scripts", "pangea_weapons.shader"), "w", newline="\n") as f:
        f.write(shader_text(metas))
    files = []
    for root, _, names in os.walk(pak):
        for n in names:
            full = os.path.join(root, n)
            rel = os.path.relpath(full, pak).replace(os.sep, "/")
            if not rel.startswith(ALLOWED) or rel.endswith(".png"):
                if rel.startswith(("models/", "icons/", "scripts/")):
                    raise SystemExit("audit: unexpected file in pak tree: %s" % rel)
                continue
            files.append((rel, full))
    files.sort()
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for rel, full in files:
            zi = zipfile.ZipInfo(rel, date_time=(2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            with open(full, "rb") as f:
                z.writestr(zi, f.read())
    data = buf.getvalue()
    sha8 = hashlib.sha256(data).hexdigest()[:8]
    os.makedirs(build, exist_ok=True)
    for old in glob.glob(os.path.join(build, "arena-weapons-*.pk3")):
        os.remove(old)
    out = os.path.join(build, "arena-weapons-%s.pk3" % sha8)
    with open(out, "wb") as f:
        f.write(data)
    print("PAK %s  %d files  %.1f KiB" % (out, len(files), len(data) / 1024.0))


if __name__ == "__main__":
    main()
